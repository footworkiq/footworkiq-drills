// Builds the per-grid strict OpenAI schemas (CONTENT-05, D-09) from the 2x3
// template docs/schema/drill.strict-schema.json.
//
// Pure: takes the parsed template and a grid id, returns a new wrapper object
// { _source, name, strict, schema }. scripts/build-strict-schemas.js writes
// the results and test/strict-schemas.test.js checks the committed files
// still match, so the per-grid files can't drift from the template.
//
// Output stays inside OpenAI's strict subset: every property required,
// additionalProperties false on every object, no const/allOf/not/if/then/else.
// Each `const` in the template becomes a single-value enum (the documented
// equivalent). Positions are {row, col} cells only, never {x, y} (D-09).
import { PRESETS } from './grid.js';

/** Grids that get a strict schema of their own. 2x3 uses the template file. */
export const STRICT_GRIDS = Object.freeze(['3x3', '3x4', '4x4']);

const range = (n) => Array.from({ length: n }, (_, i) => i + 1);

/** Replace every `const: v` in the tree with `enum: [v]`, in place. */
function constToEnum(node) {
  if (Array.isArray(node)) {
    node.forEach(constToEnum);
    return;
  }
  if (node === null || typeof node !== 'object') return;
  if ('const' in node) {
    const rebuilt = {};
    for (const [k, v] of Object.entries(node)) {
      if (k === 'const') rebuilt.enum = [v];
      else rebuilt[k] = v;
    }
    for (const k of Object.keys(node)) delete node[k];
    Object.assign(node, rebuilt);
  }
  for (const v of Object.values(node)) constToEnum(v);
}

/**
 * The strict OpenAI schema wrapper for one new grid.
 * @param {object} template parsed drill.strict-schema.json (not mutated)
 * @param {'3x3'|'3x4'|'4x4'} gridId
 */
export function buildStrictSchema(template, gridId) {
  if (!STRICT_GRIDS.includes(gridId)) {
    throw new Error(`buildStrictSchema: grid must be one of ${STRICT_GRIDS.join(', ')} (got ${gridId})`);
  }
  const { rows, cols } = PRESETS[gridId];
  const t = structuredClone(template);
  constToEnum(t);

  const schema = t.schema;
  schema.properties.schema = { type: 'string', enum: ['1.1'] };

  const metadata = schema.properties.metadata;
  metadata.properties.grid = { type: 'string', enum: [gridId] };
  if (!metadata.required.includes('grid')) metadata.required.push('grid');

  schema.$defs = {
    cell: {
      type: 'object',
      additionalProperties: false,
      required: ['row', 'col'],
      properties: {
        row: { type: 'integer', enum: range(rows) },
        col: { type: 'integer', enum: range(cols) },
      },
    },
  };

  const beat = schema.properties.sequence.items.properties;
  const cellRef = () => ({ $ref: '#/$defs/cell' });
  beat.left_foot.properties.pos = cellRef();
  beat.right_foot.properties.pos = cellRef();
  beat.ball.properties.pos = cellRef();
  beat.ball.properties.from = cellRef();
  beat.ball.properties.to = cellRef();

  return {
    _source: `GENERATED by scripts/build-strict-schemas.js from drill.strict-schema.json for grid ${gridId}; do not edit`,
    name: `drill_${gridId}`,
    strict: t.strict,
    schema,
  };
}
